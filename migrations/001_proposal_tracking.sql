-- The CPQ snapshot and its item lines remain in entities, the ERP source of truth.
CREATE TABLE IF NOT EXISTS propostas (
    proposta_id TEXT PRIMARY KEY,
    tipo TEXT GENERATED ALWAYS AS ('cpq_quote') STORED,
    chave_ip UUID NOT NULL DEFAULT gen_random_uuid(),
    numero BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    total_visualizacoes BIGINT NOT NULL DEFAULT 0 CHECK (total_visualizacoes >= 0),
    ultima_visualizacao_em TIMESTAMPTZ,
    ultimo_canal TEXT CHECK (ultimo_canal IN ('whatsapp','email','link_direto')),
    FOREIGN KEY (tipo, proposta_id) REFERENCES entities(kind,id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS proposta_links (
    token UUID PRIMARY KEY,
    proposta_id TEXT NOT NULL REFERENCES propostas(proposta_id) ON DELETE CASCADE,
    canal TEXT NOT NULL CHECK (canal IN ('whatsapp','email','link_direto')),
    UNIQUE (proposta_id, canal)
);
CREATE TABLE IF NOT EXISTS proposta_logs_abertura (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    proposta_id TEXT NOT NULL REFERENCES propostas(proposta_id) ON DELETE CASCADE,
    vendedor_id TEXT NOT NULL REFERENCES app_users(username),
    canal TEXT NOT NULL CHECK (canal IN ('whatsapp','email','link_direto')),
    user_agent VARCHAR(512) NOT NULL,
    dispositivo TEXT NOT NULL CHECK (dispositivo IN ('mobile','desktop')),
    ip_hash CHAR(64) NOT NULL,
    visualizado_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    lido_em TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS proposta_aberturas_historico ON proposta_logs_abertura(proposta_id, id DESC);
CREATE INDEX IF NOT EXISTS proposta_aberturas_pendentes ON proposta_logs_abertura(vendedor_id, id DESC) WHERE lido_em IS NULL;
CREATE TABLE IF NOT EXISTS regras_inatividade (
    usuario TEXT NOT NULL REFERENCES app_users(username),
    escopo TEXT NOT NULL CHECK (escopo IN ('propostas','negocios')),
    dias_atencao INTEGER NOT NULL,
    dias_risco INTEGER NOT NULL,
    dias_critico INTEGER NOT NULL,
    acoes_validas JSONB NOT NULL CHECK (jsonb_typeof(acoes_validas) = 'array'),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (usuario, escopo),
    CHECK (0 < dias_atencao AND dias_atencao < dias_risco AND dias_risco < dias_critico AND dias_critico <= 3650)
);
CREATE TABLE IF NOT EXISTS contatos_inatividade (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tipo TEXT NOT NULL CHECK (tipo IN ('cpq_quote','opportunity')),
    registro_id TEXT NOT NULL,
    autor TEXT NOT NULL REFERENCES app_users(username),
    acao TEXT NOT NULL CHECK (acao IN ('ligacao','email_enviado','email_recebido','reuniao_agendada','reuniao_realizada','proposta_enviada','interacao_comercial')),
    canal TEXT NOT NULL CHECK (canal IN ('telefone','email','whatsapp','presencial','video','link_direto','outro')),
    evidencia VARCHAR(1000) NOT NULL CHECK (length(trim(evidencia)) >= 3),
    ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (tipo, registro_id) REFERENCES entities(kind,id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS contatos_inatividade_registro ON contatos_inatividade(tipo, registro_id, ocorrido_em DESC, id DESC);
